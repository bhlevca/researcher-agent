"""Deterministic grammar exercises for French, German and Romanian.

The rule from the math tutor applies here for the same reason: **no language
model produces an exercise or its answer.** Every answer printed on a grammar
sheet is read out of a language pack, or derived from a table in one, so the key
is correct by construction. A child marked wrong on a correct answer learns
something false and is then told it twice — once by the sheet and once by
whoever marks it.

That rule applies to *grammar*, which is rule-governed. Stories and reading
passages are generated by the model, carry a clearly labelled "model answer"
rather than an answer, and live elsewhere. Mixing the two silently is how a
worksheet ends up with a confidently wrong key.

The packs are data (``langpacks/*.yaml``), so a language is added or corrected
by editing YAML, and a form that reads wrong to a speaker can be fixed without
touching Python.
"""

from __future__ import annotations

import random
import logging
from pathlib import Path
from functools import lru_cache
from dataclasses import dataclass, field

logger = logging.getLogger(__name__)

PACK_DIR = Path(__file__).parent / "langpacks"

# Only these three have packs, so only these three get deterministic exercises.
# Everything else the chat tutor supports stays on the conversational path.
SUPPORTED = {"French": "fr", "German": "de", "Romanian": "ro"}

_CEFR = ["A1", "A2", "B1", "B2", "C1", "C2"]


# Prompts follow the same convention as the math tutor: prose inside \text{},
# mathematics bare. printing.mixed() then pulls the prose back out so a long
# question wraps instead of running off the page. Writing a literal "$" into a
# prompt would nest dollar signs and fail to compile.
BLANK = r"\rule{2.5cm}{0.4pt}"
BLANK_WIDE = r"\rule{3.5cm}{0.4pt}"
ARROW = r"\rightarrow"


def _P(*parts: str) -> str:
    """Build a prompt, wrapping the words and leaving the LaTeX alone."""
    out = []
    for part in parts:
        if not part:
            continue
        if part.startswith("\\"):          # already LaTeX
            out.append(part)
        else:
            out.append(r"\text{" + part + "}")
    return "".join(out)


@dataclass
class Exercise:
    """One exercise, with its answer already known."""

    prompt: str                       # what the child reads
    answer: str                       # the correct answer, from the pack
    hint: str = ""                    # usually the English gloss
    skill: str = ""
    level: str = ""
    lang: str = ""
    # Multiple choice when the format calls for it; empty means write-in.
    options: list[str] = field(default_factory=list)

    def as_dict(self) -> dict:
        return {"prompt": self.prompt, "answer": self.answer, "hint": self.hint,
                "skill": self.skill, "level": self.level, "lang": self.lang,
                "options": self.options}


def pack_code(language: str) -> str | None:
    """Map a UI language name to its pack code, or None if it has no pack."""
    return SUPPORTED.get((language or "").strip().title())


@lru_cache(maxsize=8)
def load_pack(code: str) -> dict:
    import yaml

    path = PACK_DIR / f"{code}.yaml"
    if not path.is_file():
        raise ValueError(f"No language pack for '{code}'")
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def _at_or_below(items: list[dict], level: str) -> list[dict]:
    """Entries a student at *level* has plausibly met.

    An A1 sheet reaching for the subjunctive is not a hard exercise, it is a
    badly made one.
    """
    ceiling = _CEFR.index(level) if level in _CEFR else 1
    out = [i for i in items if _CEFR.index(i.get("level", "A1")) <= ceiling]
    return out or items


# ---------------------------------------------------------------------------
# Language-specific helpers
# ---------------------------------------------------------------------------


def _fr_elide(word: str, following: str, pack: dict) -> str:
    """French elision: je + ai -> j', le + arbre -> l'.

    Getting this wrong is the single most visible way a French sheet announces
    that it was generated by someone who does not speak French.
    """
    vowels = pack["meta"].get("vowels", "aeiou")
    if following and following[0].lower() in vowels:
        if word in ("je", "le", "la", "ne", "de", "que", "me", "te", "se"):
            return word[:-1] + "'"
    return word + " "


def _fr_join(pronoun: str, form: str, pack: dict) -> str:
    joined = _fr_elide(pronoun, form, pack)
    return f"{joined}{form}" if joined.endswith("'") else f"{joined}{form}"


def _de_perfekt(verb: dict, pronoun: str, pack: dict) -> str:
    """ich habe gesprochen / ich bin gegangen — auxiliary conjugated, participle last."""
    aux_name = verb["perfekt"]["aux"]
    aux = next(v for v in pack["verbs"] if v["inf"] == aux_name)
    return f"{pronoun} {aux['present'][pronoun]} {verb['perfekt']['pp']}"


def _fr_passe_compose(verb: dict, pronoun: str, pack: dict) -> str:
    aux_name = verb["passe_compose"]["aux"]
    aux = next(v for v in pack["verbs"] if v["inf"] == aux_name)
    aux_form = aux["present"][pronoun]
    pp = verb["passe_compose"]["pp"]
    # Verbs taking être agree with the subject; masculine is the default when
    # the subject's gender is not stated.
    if aux_name == "être" and pronoun in ("nous", "vous", "ils"):
        pp += "s"
    return f"{_fr_join(pronoun, aux_form, pack)} {pp}"


def _ro_perfect(verb: dict, pronoun: str, pack: dict) -> str:
    return f"{pronoun} {pack['perfect_aux'][pronoun]} {verb['participle']}"


def _ro_future(verb: dict, pronoun: str, pack: dict) -> str:
    return f"{pronoun} {pack['future_aux'][pronoun]} {verb['bare_inf']}"



def gen_conjugation(rng: random.Random, pack: dict, level: str) -> Exercise:
    """Give the infinitive and a pronoun, ask for the form."""
    verb = rng.choice(_at_or_below(pack["verbs"], level))
    tense = rng.choice([t for t in ("present", "imparfait", "imperfect",
                                    "praeteritum", "futur")
                        if t in verb])
    pronoun = rng.choice(pack["pronouns"])
    form = verb[tense][pronoun]
    code = pack["meta"]["code"]
    shown = _fr_join(pronoun, form, pack) if code == "fr" else f"{pronoun} {form}"
    answer = shown if code == "fr" else form
    return Exercise(
        prompt=_P(f"({verb['inf']}, {_TENSE_NAME[code][tense]}) {pronoun} ", BLANK),
        answer=answer, hint=verb["gloss"], skill="conjugation",
        level=level, lang=code)


_TENSE_NAME = {
    "fr": {"present": "présent", "imparfait": "imparfait", "futur": "futur"},
    "de": {"present": "Präsens", "praeteritum": "Präteritum"},
    "ro": {"present": "prezent", "imperfect": "imperfect"},
}


def gen_tense_transform(rng: random.Random, pack: dict, level: str) -> Exercise:
    """Rewrite a present-tense sentence in a compound past or future."""
    code = pack["meta"]["code"]
    verb = rng.choice(_at_or_below(pack["verbs"], level))
    pronoun = rng.choice(pack["pronouns"])
    present = verb["present"][pronoun]

    if code == "fr":
        given = _fr_join(pronoun, present, pack)
        target, name = _fr_passe_compose(verb, pronoun, pack), "passé composé"
    elif code == "de":
        given = f"{pronoun} {present}"
        target, name = _de_perfekt(verb, pronoun, pack), "Perfekt"
    else:
        given = f"{pronoun} {present}"
        if rng.random() < 0.5:
            target, name = _ro_perfect(verb, pronoun, pack), "perfect compus"
        else:
            target, name = _ro_future(verb, pronoun, pack), "viitor"
    return Exercise(
        prompt=_P(given + " ", ARROW, f" ({name})"),
        answer=target, hint=verb["gloss"], skill="tense_transform",
        level=level, lang=code)


def gen_gender_article(rng: random.Random, pack: dict, level: str) -> Exercise:
    """The definite article — which is a different exercise in each language."""
    code = pack["meta"]["code"]
    noun = rng.choice(_at_or_below(pack["nouns"], level))

    if code == "ro":
        # Enclitic: the article is a suffix, so the task is to articulate the
        # noun rather than to choose a word to put in front of it.
        return Exercise(
            prompt=_P(noun["word"] + " ", ARROW, " ", BLANK_WIDE,
                      " (articulat)"),
            answer=noun["def_sg"], hint=noun["gloss"],
            skill="gender_article", level=level, lang=code)

    if code == "de":
        case = rng.choice(["nom", "akk", "dat"])
        art = pack["articles"]["definite"][case][noun["gender"]]
        return Exercise(
            prompt=_P("", BLANK, f" {noun['word']} ({_DE_CASE[case]})"),
            answer=art, hint=noun["gloss"],
            options=sorted({pack["articles"]["definite"][case][g]
                            for g in ("m", "f", "n")}),
            skill="gender_article", level=level, lang=code)

    art = pack["articles"]["definite"]
    vowels = pack["meta"]["vowels"]
    answer = (art["elided"] if noun["word"][0].lower() in vowels
              else art[noun["gender"]])
    return Exercise(
        prompt=_P("", BLANK, f" {noun['word']}"),
        answer=f"{answer}{noun['word']}" if answer.endswith("'")
        else f"{answer} {noun['word']}",
        hint=noun["gloss"], options=[art["m"], art["f"], art["elided"]],
        skill="gender_article", level=level, lang=code)


_DE_CASE = {"nom": "Nominativ", "akk": "Akkusativ", "dat": "Dativ",
            "gen": "Genitiv"}


def gen_plural(rng: random.Random, pack: dict, level: str) -> Exercise:
    noun = rng.choice(_at_or_below(pack["nouns"], level))
    code = pack["meta"]["code"]
    lead = {"fr": "un", "de": "ein", "ro": "un"}[code]
    if code == "fr":
        lead = pack["articles"]["indefinite"][noun["gender"]]
    elif code == "ro":
        lead = pack["articles"]["indefinite"][noun["gender"]]
    elif code == "de":
        lead = pack["articles"]["indefinite"]["nom"][noun["gender"]]
    return Exercise(
        prompt=_P(f"{lead} {noun['word']} ", ARROW, " ", BLANK_WIDE),
        answer=noun["plural"], hint=noun["gloss"], skill="plural",
        level=level, lang=code)


def gen_adjective_agreement(rng: random.Random, pack: dict, level: str) -> Exercise:
    """Agreement — inflected from the pack, or derived from German's tables."""
    code = pack["meta"]["code"]
    noun = rng.choice(_at_or_below(pack["nouns"], level))
    adj = rng.choice(_at_or_below(pack["adjectives"], level))
    plural = rng.random() < 0.35

    if code == "de":
        # Derived from the ending tables, so none of the 48 endings can be
        # mistyped into the answer key.
        case = rng.choice(["nom", "akk", "dat"])
        kind = rng.choice(["weak", "mixed"])
        if kind == "weak":
            art = pack["articles"]["definite"][case][noun["gender"]]
        else:
            art = pack["articles"]["indefinite"][case][noun["gender"]]
        ending = pack["adjective_endings"][kind][case][noun["gender"]]
        return Exercise(
            prompt=_P(f"{art} ", BLANK, f" {noun['word']} "
                      f"({adj['word']}, {_DE_CASE[case]})"),
            answer=f"{adj['word']}{ending}",
            hint=f"{adj['gloss']} {noun['gloss']}",
            skill="adjective_agreement", level=level, lang=code)

    key = ("fpl" if plural else "f") if noun["gender"] == "f" else \
          ("mpl" if plural else "word")
    form = adj[key] if key != "word" else adj["word"]
    word = noun["plural"] if plural else noun["word"]
    blank = BLANK

    if code == "fr":
        art = pack["articles"]["definite"]["pl" if plural else noun["gender"]]
        # A small group of common adjectives goes BEFORE the noun — petit,
        # grand, beau, vieux, nouveau. Asking for "le livre petit" would drill
        # word order that is wrong.
        if adj.get("prenominal"):
            # beau/vieux/nouveau become bel/vieil/nouvel before a vowel.
            if (not plural and noun["gender"] == "m"
                    and word[0].lower() in pack["meta"]["vowels"]):
                form = adj.get("m_vowel", form)
            # Elision follows the NEXT word, which is now the adjective: the
            # answer is "la petite eau", not "l' petite eau".
            lead = _fr_elide(art, form, pack)
            body = (lead, blank, f" {word}")
        else:
            # "le enfant" is not French; the article elides before a vowel.
            body = (_fr_elide(art, word, pack) + word + " ", blank, "")
    else:
        # Romanian adjectives follow the noun.
        art = "" if plural else pack["articles"]["indefinite"][noun["gender"]]
        body = (f"{art + ' ' if art else ''}{word} ", blank, "")

    return Exercise(
        prompt=_P(*body, f" ({adj['word']})"),
        answer=form, hint=f"{noun['gloss']}, {adj['gloss']}",
        skill="adjective_agreement", level=level, lang=code)


def gen_german_case(rng: random.Random, pack: dict, level: str) -> Exercise:
    """Case selection after a verb or preposition — the German sticking point."""
    noun = rng.choice(_at_or_below(pack["nouns"], level))
    frame, case = rng.choice([
        ("Ich sehe {blank} {noun}.", "akk"),
        ("Das ist {blank} {noun}.", "nom"),
        ("Ich gebe {blank} {noun} ein Buch.", "dat"),
        ("Er kommt mit {blank} {noun}.", "dat"),
        ("Ich kaufe {blank} {noun}.", "akk"),
    ])
    art = pack["articles"]["definite"][case][noun["gender"]]
    before, _, after = frame.partition("{blank}")
    return Exercise(
        prompt=_P(before, BLANK,
                  after.format(noun=noun["word"]) + f" ({_DE_CASE[case]})"),
        answer=art, hint=noun["gloss"],
        options=sorted({pack["articles"]["definite"][case][g]
                        for g in ("m", "f", "n")}),
        skill="german_case", level=level, lang="de")


def gen_vocabulary(rng: random.Random, pack: dict, level: str) -> Exercise:
    """English to target language, drawn from the pack's glosses."""
    code = pack["meta"]["code"]
    pool = (_at_or_below(pack["nouns"], level) +
            _at_or_below(pack["adjectives"], level))
    item = rng.choice(pool)
    word = item["word"]
    if "gender" in item and code != "de":
        art = pack["articles"]["indefinite"]
        art = art[item["gender"]] if code != "de" else art["nom"][item["gender"]]
        word = f"{art} {word}"
    elif "gender" in item:
        word = f"{pack['articles']['definite']['nom'][item['gender']]} {word}"
    return Exercise(
        prompt=_P(item["gloss"] + " ", ARROW, " ", BLANK_WIDE),
        answer=word, skill="vocabulary", level=level, lang=code)


GENERATORS = {
    "conjugation": gen_conjugation,
    "tense_transform": gen_tense_transform,
    "gender_article": gen_gender_article,
    "plural": gen_plural,
    "adjective_agreement": gen_adjective_agreement,
    "vocabulary": gen_vocabulary,
}

# Skills that only make sense in one language.
LANG_ONLY = {"german_case": ("de", gen_german_case)}


def available_skills(language: str) -> list[dict]:
    """Skills that can be generated for *language*, with readable names."""
    code = pack_code(language)
    if not code:
        return []
    out = [{"id": k, "name": _SKILL_NAMES[k]} for k in GENERATORS]
    out += [{"id": k, "name": _SKILL_NAMES[k]}
            for k, (c, _) in LANG_ONLY.items() if c == code]
    return out


_SKILL_NAMES = {
    "conjugation": "Verb conjugation",
    "tense_transform": "Changing tense",
    "gender_article": "Gender and articles",
    "plural": "Plurals",
    "adjective_agreement": "Adjective agreement",
    "vocabulary": "Vocabulary (English → target)",
    "german_case": "Cases (nominative, accusative, dative)",
}


def generate(skill: str, language: str, level: str = "A1", count: int = 10,
             seed: int | None = None) -> list[Exercise]:
    """Generate *count* exercises. A seed makes the sheet reproducible.

    Duplicates are rejected: a pack has a finite vocabulary, so collisions are
    common and a sheet asking the same thing twice looks careless.
    """
    code = pack_code(language)
    if not code:
        raise ValueError(
            f"No language pack for '{language}'. Deterministic exercises exist "
            f"for {', '.join(sorted(SUPPORTED))}.")
    pack = load_pack(code)

    fn = GENERATORS.get(skill)
    if fn is None:
        only = LANG_ONLY.get(skill)
        if only and only[0] == code:
            fn = only[1]
        elif only:
            raise ValueError(f"'{skill}' applies to {only[0]}, not {code}")
        else:
            raise ValueError(f"No generator for skill '{skill}'")

    rng = random.Random(seed)
    out: list[Exercise] = []
    seen: set[str] = set()
    attempts = 0
    while len(out) < count and attempts < count * 40:
        attempts += 1
        try:
            ex = fn(rng, pack, level)
        except Exception as e:                       # one bad draw must not
            logger.warning("[tutor] %s failed: %s", skill, e)   # kill the sheet
            continue
        key = f"{ex.prompt}|{ex.answer}"
        if key in seen:
            continue
        seen.add(key)
        out.append(ex)
    return out
